from questions import C, box, ch, dlg, grid, lab, lines, p


def order(items, correct, target):
    """items[correct] 를 target 번째(0부터)에 두고 나머지는 원래 순서를 유지한다."""
    rest = [x for i, x in enumerate(items) if i != correct]
    rest.insert(target, items[correct])
    return rest


Q, ANS, EXPL = [], [], []


def add(stem, body, ans, expl):
    Q.append((stem, body))
    ANS.append(C[ans])
    EXPL.append(expl)


def stmt(stem, pre, items, correct, target, expl, kind=ch):
    """진술형 문항: items 중 correct 가 정답, target 위치(0부터)로 옮긴다."""
    add(stem, pre + kind(*order(items, correct, target)), target, expl)


