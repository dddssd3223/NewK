def cons_table(blank):
    """자음 체계표(조음 방법·발성 유형 × 조음 위치). blank: {자음: 빈칸 기호}."""
    def c(x):
        return blank.get(x, x)
    rows = [("파열음", "예사소리", ["ㅂ", "ㄷ", "", "ㄱ", ""]),
            ("", "거센소리", ["ㅍ", "ㅌ", "", "ㅋ", ""]),
            ("", "된소리", ["ㅃ", "ㄸ", "", "ㄲ", ""]),
            ("파찰음", "예사소리", ["", "", "ㅈ", "", ""]),
            ("", "거센소리", ["", "", "ㅊ", "", ""]),
            ("", "된소리", ["", "", "ㅉ", "", ""]),
            ("마찰음", "예사소리", ["", "ㅅ", "", "", "ㅎ"]),
            ("", "된소리", ["", "ㅆ", "", "", None]),
            ("비음", None, ["ㅁ", "ㄴ", "", "ㅇ", ""]),
            ("유음", None, ["", "ㄹ", "", "", ""])]
    out = ['<table class="t vt"><tr><th colspan="2" style="width:26%">조음 방법·발성 유형 ＼ 조음 위치</th>'
           '<th>입술<br/>소리</th><th>잇몸<br/>소리</th><th>센입<br/>천장<br/>소리</th><th>여린<br/>입천장<br/>소리</th>'
           '<th>목청<br/>소리</th></tr>']
    for i, (m, k, cells) in enumerate(rows):
        tr = "<tr>"
        if k is None:
            tr += f'<td class="ctr" colspan="2">{m}</td>'
        else:
            if m:
                tr += f'<td class="ctr" rowspan="{3 if m != "마찰음" else 2}">{m}</td>'
            tr += f'<td class="ctr">{k}</td>'
        for j, x in enumerate(cells):
            if x is None:
                continue
            if x == "ㅎ":
                tr += f'<td class="ctr" rowspan="2">{c(x)}</td>'
            else:
                tr += f'<td class="ctr">{c(x)}</td>'
        out.append(tr + "</tr>")
    return "".join(out) + "</table>"


