def pick(items, correct, target):
    """items[correct] 를 target 자리로 옮긴 목록."""
    return order(items, correct, target)


def rows_w(head, data, widths):
    """선지 번호 표(열 너비 % 지정). widths 는 번호 칸을 포함한 열별 %."""
    th = "".join(f'<th style="width:{w}%">{h}</th>' for h, w in zip([""] + head, widths))
    return ('<table class="t hz">' + "<tr>" + th + "</tr>"
            + "".join(f"<tr><td>{C[i]}</td>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>"
                      for i, r in enumerate(data))
            + "</table>")


