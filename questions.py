"""2학년 화법과 언어 프린트(음운론·발음)의 객관식 문제.

각 문제는 (발문, 본문 HTML) 묶음이다. 문항 번호는 make_template.py 가 붙인다.
본문에 쓰는 도우미:
  box(제목, 내용)   : <보기>·<조건> 상자
  ch(*선지)         : 한 줄에 하나씩, 둘째 줄부터 들여쓰기
  grid(선지들, n)   : 짧은 선지를 n 칸으로 나란히
  lab(선지들)       : '① ㉠ : …' 처럼 머리말 뒤에 둘째 줄을 맞춰 들여쓰기
  img(이름)         : 원본 그림 (assets/figs/이름.png)
"""

C = "①②③④⑤"


def box(title, inner, cls="box"):
    head = f'<p class="bt">&lt; {title} &gt;</p>' if title else ""
    return f'<div class="{cls}">{head}{inner}</div>'


def p(text, cls=None):
    return f'<p class="{cls}">{text}</p>' if cls else f"<p>{text}</p>"


def ch(*items):
    return "".join(p(f"{C[i]} {t}", "c") for i, t in enumerate(items))


def lab(*items):
    return "".join(p(f"{C[i]} {t}", "c3") for i, t in enumerate(items))


def grid(items, n=3):
    cells = [f"{C[i]} {t}" for i, t in enumerate(items)]
    rows = [cells[i:i + n] for i in range(0, len(cells), n)]
    return ('<table class="g">' + "".join(
        "<tr>" + "".join(f"<td>{c}</td>" for c in r) + "<td></td>" * (n - len(r)) + "</tr>"
        for r in rows) + "</table>")


def img(name, width="100%"):
    return f'<p class="fig"><img src="figs/{name}.png" style="width:{width}"/></p>'


def figure(name, height):
    """make_template.py 가 직접 그리는 그림 자리 (높이 pt)."""
    return f'<div class="fig-{name}" style="height:{height}pt"></div>'


def lines(*rows, cls="l"):
    return "".join(p(r, cls) for r in rows)


